<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\Response;

/**
 * ⭐⭐⭐ الحساب الموقوف بيتقفل **فوراً**.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⭐ الثغرة اللي كان موجود
 *
 * `AuthController::login` بيتأكد إن `status === 'active'` — بس
 * **وقت الدخول بس**.
 *
 * فالنماريو ده كان شغّال ١٠٠٪:
 *
 *   1. الأدAdmin بيوقف حساب موظف
 *   2. التوكين بتاع الموظف **صادر قبل الوقفة** — ولسه صالح
 *   3. الموظف بيفتح التطبيق → **بيدخل عادي**
 *
 * ⭐ والأسوأ: `config/sanctum.php` كان فيه `'expiration' => null`
 * — فالتوكين صالح **للأبد**. يعني الوقف ما كانش بيعمل حاجة
 * فعلياً غير لو المستخدم عمل تسجيل دخول جديد.
 *
 * ⭐ ده تصعيد صلاحيات كامل: من غيره، الوقف أداة وهمية.
 *
 * ═══════════════════════════════════════════════════════════════
 * ليه 403 مش 401
 *
 * ⭐ التوكين **صالح تقنياً** — فـ 401 (يعني «مين أنت؟») غلط
 * ومضلّل. الـ403 بيقول «أنا عارفك، بس مش مسموح» — وده بالظبط
 * اللي حصل.
 *
 * ⭐ الـ frontend يقدر يفرق بين 401 (-session منتهية، وروّحه
 * صفحة الدخول) و403 (الحساب موقوف، وعرض رسالة مناسبة).
 *
 * ═══════════════════════════════════════════════════════════════
 * القيم المشمولة
 *
 * `active` بس هي اللي يعدّي. `suspended` و `inactive` مرفوضين:
 *
 *   • `suspended` — الأدمن وقفه مؤقتاً
 *   • `inactive`  — الحساب ميت (مغادر مثلاً)
 *
 * ⭐ الاتنين مختلفين في السبب بس **نفس النتيجة**: مش بيفتح.
 *
 * @see \Tests\Feature\LoginHardeningTest
 */
class EnsureAccountActive
{
    public function handle(Request $request, Closure $next): Response
    {
        $user = $request->user();

        // ⭐ مافيش user = الراوت عام. `Authenticate` هو المسؤول
        // عن الـ401 لما الراوت محمي والتوكين غلط.
        if (! $user) {
            return $next($request);
        }

        if ($user->status === 'active') {
            return $next($request);
        }

        return response()->json([
            'message' => 'الحساب مش نشط — كلّم إدارة الأكاديمية.',
            'status' => $user->status,
        ], 403);
    }
}
