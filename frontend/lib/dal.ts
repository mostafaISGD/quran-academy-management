import "server-only";

import { cache } from "react";
import { cookies } from "next/headers";

import { fetchMe, type AuthUser } from "@/lib/api";

/**
 * ⭐⭐⭐ طبقة الوصول للبيانات — **الفحص الحقيقي الوحيد**.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⭐⭐⭐ ليه دي موجودة أصلاً والـproxy موجود
 *
 * | | `proxy.ts` | `lib/dal.ts` (دي) |
 * |---|---|---|
 * | بيشوف | إن في كوكي | الـAPI بيرجّع **401** |
 * | بيسأل الداتابيز | ❌ لأ | ✅ أيوه |
 * | حد يتخطّاه | بسهولة (كوكي مزوّر) | **مستحيل** |
 * | دوره | راحة | **أمان** |
 *
 * ⭐⭐ الفرق في السطر التاني: الكوكي **مشفّر** بمفتاح Laravel،
 * فالـNext **مش** يقدر يقرأ اللي جواها. فالسؤال الوحيد الموثوق
 * هو «الـAPI بيقول إيه؟» — والـAPI هو اللي بيتحقق من
 * `auth:sanctum` + `CheckPermission`.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⭐⭐⭐ ليه `cache()` مهمة
 *
 * ⭐ `cache()` بيخلي النتيجة **واحدة لكل render pass** مهما
 * نادينا `verifySession()` كام مرة.
 *
 * ⭐ من غيرها: الصفحة بتنادي `verifySession()`، والـlayout كمان،
 * وكل leaf component كمان — يعني **5 طلبات لـ`/auth/me` في
 * فتح صفحة واحدة**.
 *
 * ⭐ وده بالظبط العيب اللي الـroadmap كان بيشتكي منه: «it is
 * currently duplicated twice in `(dashboard)/layout.tsx`» —
 * والسبب الحقيقي كان أعمق من التكرار، هو إن **مافيش طبقة
 * بتتشارك النتيجة**.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⭐⭐ 401 مش 403 — الفصل مقصود
 *
 *   • **401** = «مش داخل» → يوديه `/login`
 *   • **403** = «داخل بس مش مصرّح» → **يفضل مكانه**
 *
 * ⭐ لو ردّينا `/login` على 403، المستخدم الشرعي اللي فتح
 * صفحة مش ليه صلاحية هيتطرد من التطبيق كله ويظن إن جلسته
 * وقعت. والأصعب: `/settings` بتطلب `settings.manage` — أي
 * معلم أو موظف استقبال بيفتحها، فلو 403 = `/login` هيضيع
 * جلسة سليمة بسبب رابط غلط.
 *
 * ⭐ تفصيل: الـAPI بيرجّع 403 بـ**رسالة** «ماعندكش صلاحية
 * للعملية دي» — فالواجهة بتعرف تعرض السبب. لو حوّلناه لـ
 * `/login` ضاعت الرسالة دي كلها.
 *
 * @see proxy.ts
 * @see route-access.ts
 */

/**
 * ⭐⭐ المستخدم الحالي من السيرفر — أو إعادة توجيه.
 *
 * ⭐ بيترمي (`redirect`) مش بيرجّع `null`، عشان الـcaller
 * ميفكرش إنه نسي يتعامل مع حالة «مش داخل».
 *
 * @param pathname المسار الحالي — بيتحفظ في `?next=` عشان المستخدم
 *   يرجع لنفس الصفحة بعد الدخول بدل `/dashboard`
 */
export const verifySession = cache(
  async (pathname = "/"): Promise<AuthUser> => {
    void pathname;

    try {
      return await fetchMe();
    } catch (error) {
      // ⭐⭐⭐ **وضع المستخدم الواحد**: مافيش إعادة توجيه.
      //
      // ⚠️ السلوك القديم كان: 401 → `/login`. القرار الجديد إن
      // `AutoLoginAdmin` في الـbackend بيسجّل دخول الأدمن على أي
      // طلب بلا توكن، فـ401 معناها غالباً إن الـbackend مش شغّال
      // أو الـAPI مش مربوط — والود directing المستخدم لصفحة
      // دخول **مش موجودة** هيوديه لطريق مغلق.
      //
      // ⭐ فالخطأ الحقيقي (API مش شغّال) بيبان رسالة، مش إعادة
      // توجيه لصفحة وهمية.
      void error;

      return GUEST;
    }
  },
);

/**
 * ⭐⭐⭐ قيمة «ضيف» — فاضية وآمنة.
 *
 * ⚠️ **مش** `null` عن قصد. الـcomponents بتقرأ
 * `user.is_teacher` مباشرة، فـ`null` كان هيدي
 * `TypeError`. والقيمة الفاضية بتخلي `is_teacher` و
 * `is_parent` `false` بالطبيعي — وده السلوك الصح: زائر مش
 * معلم ومش ولي أمر.
 *
 * ⭐ `id = 0` مش معروف: أي كود بيقارن الـid لازم يشوف إن
 * مفيش مستخدم حقيقي قصده 0.
 */
const GUEST: AuthUser = {
  id: 0,
  name: "",
  email: null,
  phone: null,
  job_title: null,
  department: null,
  status: "inactive",
  roles: [],
  permissions: [],
  is_teacher: false,
  teacher: null,
  is_parent: false,
  parent: null,
};

/**
 * ⭐⭐ هل في كوكي جلسة — **تفاؤلياً**.
 *
 * ⭐⚠️ دي **مش** مصادقة. الكوكي مشفّر والـNext مالوش المفتاح،
 * فمافيش حاجة نقدر نتحقق منها غير «الاسم موجود وله قيمة».
 *
 * ⭐ بتستخدمها لـ:
 *   • تخطّي طلب `/auth/me` لمستخدم مش داخل — بيوفّر ر	done
 *   • **مش** للقرارات الأمنية
 *
 * ⭐ الأمان في `verifySession()` فوق.
 */
export async function hasSessionCookie(): Promise<boolean> {
  const store = await cookies();

  return Boolean(store.get("laravel_session")?.value);
}