/**
 * يحوّل أيام الأسبوع لمفتاح نصّي ثابت.
 *
 * @param weekdays أرقام الأيام (0=الأحد)
 * @returns نص زي `"0,2,4"` — ثابت طالما المحتوى واحد
 */
export function weekdaysKey(weekdays: number[]): string {
  return [...weekdays]
    .sort((a, b) => a - b)
    .join(",");
}

/**
 * يرجّع الأيام من المفتاح — العكس بتاع {@link weekdaysKey}.
 *
 * @param key نص زي `"0,2,4"`
 * @returns مصفوفة أرقام، أو `[]` لو المفتاح فاضي
 */
export function parseWeekdaysKey(key: string): number[] {
  return key === "" ? [] : key.split(",").map(Number);
}
